"""Уплатницы для оплаты наличными: реквизиты из образцов в решениях, шифра 1xx, IPS QR.

Ошибка здесь дорогая и тихая: неверный позив на број — деньги ушли, обязанность осталась,
и видно это только по опомене. Поэтому реквизиты не набираются, а читаются из образцов,
которые налоговая сама печатает в решении, — и тесты держат именно этот разбор.

Текст синтетический: форма настоящая (как её отдаёт pdftotext -layout), позив и имя
выдуманы. Уплатные счета публичные — они одинаковы у всех.
"""
from decimal import Decimal

import pay_slips as ps

SLIP = """
                                                             НАЛОГ ЗА УПЛАТУ
                                   шифра
уплатилац                          плаћања     валута        износ
PREZIME IME PR GRAD
                                      253         дин.
                                   рачун примаоца
сврха уплате                                         {account}
                                   модел и позив на број (одобрење)
{purpose}
                                       97                 {ref}
прималац

Пореска управа Републике Србије




                                                             NBS IPS QR KOD
"""

RESDOP = ("""
Месец         Основица доприноса за         Допринос за         Допринос за          Допринос за
Октобар                99.779,25              23.947,02            10.277,26               748,34
Новембар               99.779,25              23.947,02            10.277,26               748,34
""" + SLIP.format(account='840-721313843-74', purpose='Допринос за ПИО за 2026. годину',
                  ref='1100000000000000001')
    + SLIP.format(account='840-721313843-74', purpose='Допринос за ПИО за 2027. годину',
                  ref='2200000000000000002'))

RESPOR = """
      Месечна аконтациона обавеза пореза у 2026. години износи 9.977,93 динара, обрачуната на
"""


def test_sample_slips_give_requisites_per_year():
    """Из образцов — счёт, модель, позив, сврха и прималац, у каждого года свои."""
    slips = ps.sample_slips(RESDOP)
    assert [(s['year'], s['account'], s['model'], s['ref']) for s in slips] == [
        (2026, '840-721313843-74', '97', '1100000000000000001'),
        (2027, '840-721313843-74', '97', '2200000000000000002')]
    assert slips[0]['purpose'] == 'Допринос за ПИО за 2026. годину'
    assert slips[0]['recipient'] == 'Пореска управа Републике Србије'
    assert slips[0]['code'] == '253'


def test_amounts_come_from_decisions():
    """Порез — месячная аконтация из решения, доприносы — строка месяца в таблице."""
    assert ps.porez_amount(RESPOR, 2026) == Decimal('9977.93')
    assert ps.doprinos_amounts(RESDOP, 10) == (Decimal('23947.02'), Decimal('10277.26'),
                                               Decimal('748.34'))
    assert ps.doprinos_amounts(RESDOP, 12) is None


def test_cash_code_changes_only_first_digit():
    """Наличными — 1xx: способ оплаты в первой цифре, основание не трогается."""
    assert ps.cash_code('253') == '153'


def test_ips_payload():
    """Строка IPS QR: счёт в 18 цифр, сумма с запятой, шифра и позив без пробелов."""
    slip = {'account': '840-711122843-32', 'recipient': 'Пореска управа Републике Србије',
            'amount': Decimal('9977.93'), 'code': '153', 'purpose': 'Порез за 2026.',
            'model': '97', 'ref': '1100000000000000001'}
    assert ps.ips_payload(slip, 'PREZIME IME PR GRAD') == (
        'K:PR|V:01|C:1|R:840000071112284332|N:Пореска управа Републике Србије|'
        'I:RSD9977,93|P:PREZIME IME PR GRAD|SF:153|S:Порез за 2026.|'
        'RO:971100000000000000001')


def test_month_goes_into_purpose():
    """В сврхе — месяц: по квитанции видно, за что она; «годину» из образца уходит."""
    assert ps.month_purpose('Допринос за ПИО за 2026. годину', 2026, 10) == \
        'Допринос за ПИО за октобар 2026.'
    assert ps.month_purpose('Порез на паушални приход за 2026.', 2026, 10) == \
        'Порез на паушални приход за октобар 2026.'


def test_qr_purpose_fits_35():
    """В IPS QR сврха — до 35 знаков: длинная сокращается до месяца цифрами, а не обрезается."""
    long = 'Порез на паушални приход за октобар 2026.'
    assert ps.qr_purpose(long, 10, 2026) == 'Порез на паушални приход 10/2026'
    assert ps.qr_purpose('Допринос за ПИО за октобар 2026.', 10, 2026) == \
        'Допринос за ПИО за октобар 2026.'
